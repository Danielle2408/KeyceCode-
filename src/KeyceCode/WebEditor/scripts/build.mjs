import { cp, mkdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'dist');
const monaco = path.join(root, 'node_modules', 'monaco-editor', 'min');
const xterm = path.join(root, 'node_modules', '@xterm', 'xterm');
const fitAddon = path.join(root, 'node_modules', '@xterm', 'addon-fit');
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
await cp(path.join(root, 'src'), output, { recursive: true });
await cp(path.join(monaco, 'vs'), path.join(output, 'vs'), { recursive: true });
await cp(path.join(root, 'node_modules', 'monaco-editor', 'LICENSE'), path.join(output, 'MONACO-LICENSE.txt'));
await cp(path.join(xterm, 'lib', 'xterm.js'), path.join(output, 'xterm.js'));
await cp(path.join(xterm, 'css', 'xterm.css'), path.join(output, 'xterm.css'));
await cp(path.join(xterm, 'LICENSE'), path.join(output, 'XTERM-LICENSE.txt'));
await cp(path.join(fitAddon, 'lib', 'addon-fit.js'), path.join(output, 'addon-fit.js'));
await cp(path.join(fitAddon, 'LICENSE'), path.join(output, 'XTERM-FIT-LICENSE.txt'));
console.log(`Offline Monaco editor assets copied to ${output}`);
